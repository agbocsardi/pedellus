function toolResultsOf(requestText) {
  const messages = JSON.parse(requestText);
  return messages
    .filter((message) => message !== null && typeof message === "object" && message.role === "toolResult")
    .map((message) => ({
      toolName: typeof message.toolName === "string" ? message.toolName : "",
      isError: message.isError === true,
      text: Array.isArray(message.content)
        ? message.content.map((block) => (block?.type === "text" ? block.text : "")).join("\n")
        : "",
    }));
}

/** Text blocks of every message, for per-message provenance checks. */
function messageTexts(requestText) {
  const messages = JSON.parse(requestText);
  return messages.map((message) => {
    if (message === null || typeof message !== "object") return "";
    if (typeof message.content === "string") return message.content;
    if (!Array.isArray(message.content)) return "";
    return message.content
      .map((block) => (block?.type === "text" ? String(block.text ?? "") : ""))
      .join("\n");
  });
}

/**
 * Locate the one compaction summary message and prove the early fact is inside
 * it and nowhere else. The raw early turn carries a sentinel; the topic file
 * carries its own marker, so neither can satisfy the fact assertion.
 */
function factIsolation(requestText) {
  const texts = messageTexts(requestText);
  const summaryIndexes = texts.flatMap((text, index) => (text.includes(COMPACTION_PREFIX) ? [index] : []));
  const summaryIndex = summaryIndexes.length === 1 ? summaryIndexes[0] : -1;
  return {
    summaryCount: summaryIndexes.length,
    summaryHasFact: summaryIndex >= 0 && texts[summaryIndex].includes(FACT),
    othersHaveFact: texts.some((text, index) => index !== summaryIndex && text.includes(FACT)),
    factOccurrences: texts.join("\n").split(FACT).length - 1,
  };
}

/** True when the raw-turn sentinel appears outside the placed summary. */
function sentinelOutsideSummary(requestText) {
  const texts = messageTexts(requestText);
  const summaryIndexes = texts.flatMap((text, index) => (text.includes(COMPACTION_PREFIX) ? [index] : []));
  return texts.some((text, index) => !summaryIndexes.includes(index) && text.includes(SENTINEL));
}

/** Digits of the acceptance fact, used only to classify alternate formatting. */
const FACT_DIGITS = FACT.replace(/[^0-9]/g, "");

function compactForm(text) {
  return String(text).toLowerCase().replace(/[^a-z0-9]+/g, "");
}

/**
 * Classify how text carries the fact without recording it: exact marker, a
 * case/separator variant, digits only, or absent. Booleans, a character count
 * and a bounded hash only; the pass rule stays an exact marker match.
 */
function factFidelity(text) {
  const compact = compactForm(text);
  const exact = text.includes(FACT);
  const normalized = compact.includes(compactForm(FACT));
  const digitsPresent = FACT_DIGITS.length > 0 && compact.includes(FACT_DIGITS);
  return {
    exact,
    normalized,
    digitsPresent,
    variant: exact ? "exact" : normalized ? "normalized" : digitsPresent ? "digits-only" : "absent",
    chars: text.length,
    sha256Prefix: sha256(text).slice(0, 16),
  };
}

/** Count fact/sentinel occurrences inside and outside the placed summary. */
function occurrenceIsolation(requestText) {
  const texts = messageTexts(requestText);
  const summaryIndexes = texts.flatMap((text, index) => (text.includes(COMPACTION_PREFIX) ? [index] : []));
  const summaryIndex = summaryIndexes.length === 1 ? summaryIndexes[0] : -1;
  const summaryText = summaryIndex >= 0 ? texts[summaryIndex] : "";
  const count = (needle) => texts.reduce((total, text) => total + text.split(needle).length - 1, 0);
  const summaryFacts = summaryText.split(FACT).length - 1;
  const summarySentinels = summaryText.split(SENTINEL).length - 1;
  return {
    factInSummary: summaryFacts,
    factOutsideSummary: count(FACT) - summaryFacts,
    sentinelInSummary: summarySentinels,
    sentinelOutsideSummary: count(SENTINEL) - summarySentinels,
    factFidelityInSummary: factFidelity(summaryText),
  };
}

