async function loadCore() {
  await access(join(ROOT, "dist", "runtime.js")).catch(() => {
    throw new Error("dist/ is missing: run `npm run build` before the acceptance runner");
  });
  const aiDist = join(ROOT, "node_modules", "@earendil-works", "pi-ai", "dist");
  const chordDist = join(ROOT, "node_modules", "@earendil-works", "chord", "dist");
  const [{ openGateway }, { parseConfig }, { workspaceContextGatewayOptions }, ai, transcript, chord] = await Promise.all([
    import(pathToFileURL(join(ROOT, "dist", "runtime.js")).href),
    import(pathToFileURL(join(ROOT, "dist", "config.js")).href),
    import(pathToFileURL(join(ROOT, "dist", "context", "workspace-host.js")).href),
    import(pathToFileURL(join(aiDist, "index.js")).href),
    import(pathToFileURL(join(aiDist, "utils", "transcript.js")).href),
    import(pathToFileURL(join(chordDist, "context", "index.js")).href),
  ]);
  return {
    openGateway,
    parseConfig,
    workspaceContextGatewayOptions,
    createModels: ai.createModels,
    fauxProvider: ai.fauxProvider,
    fauxAssistantMessage: ai.fauxAssistantMessage,
    fauxToolCall: ai.fauxToolCall,
    getCurrentSystemPrompt: transcript.getCurrentSystemPrompt,
    context: chord.BACKGROUND_CONTEXT,
  };
}

function gatewayConfig(core, stateDir) {
  const model = { provider: PROVIDER, modelId: MODEL_ID };
  return core.parseConfig({
    workspace: join(stateDir, "workspace"),
    dataDir: join(stateDir, "data"),
    model,
    allowedModels: [model],
    toolAllowlist: ["read", "write", "edit"],
    workspaceContext: {
      memoryFiles: ["memory/MEMORY.md"],
      memoryManifest: true,
      skills: { disabledSkills: [] },
    },
  }, stateDir);
}

function buildProbe(core) {
  const provider = core.fauxProvider({
    provider: PROVIDER,
    models: [{ id: MODEL_ID, name: "Synthetic acceptance model" }],
  });
  const models = core.createModels();
  models.setProvider(provider.provider);
  return { provider, models, requests: [] };
}

function installer(core, probe, requestPrefix) {
  const state = { script: [], summary: undefined };
  const capture = (kind, request) => {
    const text = JSON.stringify(request.messages);
    const prompt = core.getCurrentSystemPrompt(request.messages);
    const entry = {
      kind,
      index: probe.requests.length,
      chars: text.length,
      sha256: sha256(text),
      text,
      prompt,
    };
    probe.requests.push(entry);
    return entry;
  };
  const summaryResponse = (entry) => {
    const extracted = /AURORA-[0-9]{4}/.exec(entry.text)?.[0];
    const topic = entry.text.includes(TOPIC_PATH) ? TOPIC_PATH : undefined;
    state.summary = {
      observed: true,
      extractedFact: extracted ?? null,
      extractedTopic: topic ?? null,
      requestChars: entry.chars,
      requestSha256: entry.sha256,
    };
    const body = extracted === undefined
      ? "## Critical Context\n- The acceptance code could not be extracted from this request.\n"
      : [
          "## Goal",
          "Continue the acceptance conversation while preserving its early fact.",
          "",
          "## Progress",
          "### Done",
          "- [x] Loaded the note-keeping skill body through the skill tool.",
          `- [x] Wrote and read ${topic ?? "the topic memory file"} through granted tools.`,
          "",
          "## Critical Context",
          `- Acceptance code extracted from the summarized transcript: ${extracted}`,
          `- Topic memory locator: ${topic ?? "unavailable"}`,
          "",
        ].join("\n");
    return core.fauxAssistantMessage(body, { stopReason: "stop" });
  };
  // One dispatcher serves every request until the next `setResponses`, so a
  // tool turn's follow-up generation keeps the same plan. It re-arms itself.
  const dispatcher = (request) => {
    const prompt = core.getCurrentSystemPrompt(request.messages);
    const isSummary = prompt.startsWith("You are a context summarization assistant");
    const entry = capture(isSummary ? "summary" : "generation", request);
    probe.provider.appendResponses([dispatcher]);
    if (isSummary) return summaryResponse(entry);
    const step = state.script.shift();
    if (step === undefined) throw new Error("Unexpected synthetic generation request");
    return step;
  };
  let turn = 0;
  return {
    state,
    dispatcher,
    async send(conversation, context, text, steps) {
      state.script = [...steps];
      probe.provider.setResponses([dispatcher]);
      turn += 1;
      const requestId = `${requestPrefix}-${turn}`;
      const submission = await conversation.submit({ type: "input", content: text, requestId }, context);
      const settled = await submission.wait(context);
      await conversation.waitForIdle(context);
      if (settled?.status !== "done") throw new Error(`turn ${requestId} settled as ${settled?.status}`);
      if (state.script.length !== 0) {
        throw new Error(`turn ${requestId} left ${state.script.length} planned responses unconsumed after ${probe.requests.length} requests`);
      }
    },
  };
}

async function runFirstPhase(core, stateDir, evidence) {
  const { checks, record, require } = collector("phase1", stateDir);
  const workspace = join(stateDir, "workspace");
  const context = core.context;
  const probe = buildProbe(core);
  const driver = installer(core, probe, "p1");
  const config = gatewayConfig(core, stateDir);
  let gateway;
  try {
    gateway = await core.openGateway(config, context, {
      models: probe.models,
      ...core.workspaceContextGatewayOptions(config),
    });
    const conversation = await gateway.conversationFor(SESSION_KEY, context);
    evidence.conversationId = conversation.id;
    const toolNames = async () => {
      const agent = await conversation.agent(context);
      return (agent.tools ?? []).map((tool) => (typeof tool === "string" ? tool : tool?.name));
    };

    // Default deny, then explicit grants with expiry.
    let names = await toolNames();
    require("tools.default_deny", !names.includes("read") && !names.includes("write") && !names.includes("edit"), names.join(","));
    record("skill.tool_offered", names.includes("skill"), names.join(","));

    let ceilingRejected = false;
    try {
      await gateway.grantTools(SESSION_KEY, [{ name: "bash", expiresAt: Date.now() + 60_000 }], context);
    } catch (error) {
      ceilingRejected = /outside the host tool ceiling/.test(String(error?.message ?? error));
    }
    record("tools.ceiling_rejected", ceilingRejected);

    let pastRejected = false;
    try {
      await gateway.grantTools(SESSION_KEY, [{ name: "read", expiresAt: Date.now() - 1_000 }], context);
    } catch (error) {
      pastRejected = /future integer expiresAt/.test(String(error?.message ?? error));
    }
    record("tools.past_expiry_rejected", pastRejected);

    const longExpiry = Date.now() + 600_000;
    const editExpiry = Date.now() + 8_000;
    const granted = await gateway.grantTools(SESSION_KEY, [
      { name: "read", expiresAt: longExpiry },
      { name: "write", expiresAt: longExpiry },
      { name: "edit", expiresAt: editExpiry },
    ], context);
    require("tools.granted", granted.map((grant) => grant.name).join(",") === "read,write,edit", granted.map((grant) => grant.name).join(","));
    names = await toolNames();
    record("tools.offered_after_grant", ["read", "write", "edit"].every((name) => names.includes(name)), names.join(","));

    // Skill summary in the prompt, body only through the tool.
    await driver.send(conversation, context, "Load the note-keeping skill instructions before continuing.", [
      core.fauxAssistantMessage([core.fauxToolCall("skill", { name: SKILL_NAME })], { stopReason: "toolUse" }),
      core.fauxAssistantMessage("Skill instructions reviewed; no effectful action taken."),
    ]);
    const first = probe.requests[0];
    require("skills.summary_in_prompt", first.prompt.includes(SKILL_NAME) && first.prompt.includes(SKILL_DESCRIPTION));
    require("skills.body_absent_before_load", !first.text.includes(SKILL_BODY));
    const skillResults = toolResultsOf(probe.requests[1].text).filter((result) => result.toolName === "skill");
    require("skills.body_via_tool_result", skillResults.length === 1 && skillResults[0].text.includes(SKILL_BODY), skillResults[0]?.text);

    // Early fact in a raw turn; the sentinel must not survive compaction.
    await driver.send(conversation, context,
      `Early acceptance instruction: remember the acceptance code ${FACT}. This raw early turn also contains ${SENTINEL} and it must not be replayed verbatim after compaction.`,
      [core.fauxAssistantMessage("Recorded the early instruction in this conversation.")]);

    // Topic memory write through the granted write tool.
    const topicContent = [
      "---",
      `description: ${TOPIC_DESCRIPTION}`,
      "---",
      "",
      "# Acceptance topic",
      "",
      `The acceptance code is ${FACT}. It was written through the granted write tool.`,
      "",
    ].join("\n");
    await driver.send(conversation, context,
      `Use the granted write tool to store the topic memory at ${TOPIC_PATH}.`,
      [
        core.fauxAssistantMessage([core.fauxToolCall("write", { path: TOPIC_PATH, content: topicContent })], { stopReason: "toolUse" }),
        core.fauxAssistantMessage("Topic memory written."),
      ]);
    const onDisk = await readFile(join(workspace, ...TOPIC_PATH.split("/")), "utf8");
    require("memory.write_reached_disk", onDisk.includes(FACT) && onDisk.includes(TOPIC_DESCRIPTION));
    const writeResults = toolResultsOf(probe.requests.at(-1).text).filter((result) => result.toolName === "write");
    require("memory.write_tool_result", writeResults.length === 1 && writeResults[0].text.includes(TOPIC_PATH), writeResults[0]?.text);

    // Topic memory read through the granted read tool.
    await driver.send(conversation, context,
      `Use the granted read tool to read ${TOPIC_PATH} back.`,
      [
        core.fauxAssistantMessage([core.fauxToolCall("read", { path: TOPIC_PATH })], { stopReason: "toolUse" }),
        core.fauxAssistantMessage("Topic memory read back."),
      ]);
    const readResults = toolResultsOf(probe.requests.at(-1).text).filter((result) => result.toolName === "read");
    require("memory.read_tool_result", readResults.length === 1 && readResults[0].text.includes(FACT), readResults[0]?.text);

    // Enough recent transcript for native compaction to select an old prefix.
    const fillerLine = "Synthetic filler for the offline acceptance run. It carries no real data and exists only so native compaction has an old prefix to summarize. ";
    for (let index = 1; index <= 3; index += 1) {
      const filler = fillerLine.repeat(Math.ceil(42_000 / fillerLine.length)).slice(0, 42_000);
      await driver.send(conversation, context, `Filler turn ${index}. ${filler}`,
        [core.fauxAssistantMessage(`Acknowledged synthetic filler turn ${index}.`)]);
    }

    // Wait for the short edit grant to expire, then prove the call-time check.
    const wait = editExpiry + 300 - Date.now();
    if (wait > 0) await sleep(Math.min(wait, 15_000));
    const active = await gateway.listToolGrants(SESSION_KEY, context);
    const activeNames = active.map((grant) => grant.name);
    require("tools.expired_pruned", !activeNames.includes("edit") && activeNames.includes("read") && activeNames.includes("write"), activeNames.join(","));
    await driver.send(conversation, context, "Try the expired edit grant once.",
      [
        core.fauxAssistantMessage([core.fauxToolCall("edit", { path: TOPIC_PATH, oldText: "Acceptance topic", newText: "Acceptance topic" })], { stopReason: "toolUse" }),
        core.fauxAssistantMessage("The edit was refused; continuing without it."),
      ]);
    const blocked = toolResultsOf(probe.requests.at(-1).text).filter((result) => result.toolName === "edit");
    require("tools.expired_call_blocked", blocked.length === 1 && /grant expired/.test(blocked[0].text), blocked[0]?.text);

    // Native manual compaction, summarized from the actual request.
    driver.state.script = [];
    probe.provider.setResponses([driver.dispatcher]);
    const taskId = await conversation.compact(undefined, context);
    const deadline = Date.now() + COMPACTION_WAIT_MS;
    let task;
    while (Date.now() < deadline) {
      task = await gateway.harness.getTask(taskId, context);
      if (task?.state?.status === "terminal") break;
      await sleep(25);
    }
    await conversation.waitForIdle(context);
    require("compaction.task_terminal", task?.state?.status === "terminal", task?.state?.status);
    const outcome = task?.state?.outcome;
    require("compaction.task_completed", outcome?.status === "completed", outcome?.status);
    const summary = driver.state.summary;
    require("compaction.summary_request_observed", summary !== undefined);
    require("compaction.fact_extracted_from_request", summary?.extractedFact === FACT, summary?.extractedFact ?? "none");
    require("compaction.topic_extracted_from_request", summary?.extractedTopic === TOPIC_PATH, summary?.extractedTopic ?? "none");

    let view;
    const headDeadline = Date.now() + 10_000;
    while (Date.now() < headDeadline) {
      view = await conversation.context(context);
      if (view.head !== undefined) break;
      await sleep(25);
    }
    const messages = JSON.stringify(view?.messages ?? []);
    require("compaction.summary_head_placed", view?.head !== undefined);
    require("compaction.summary_visible", messages.includes(COMPACTION_PREFIX) && messages.includes(FACT));
    require("compaction.original_turn_absent", !messages.includes(SENTINEL));
    require("compaction.fact_only_in_summary", messages.split(FACT).length - 1 === 1, `${messages.split(FACT).length - 1} occurrences`);

    const summaryEntry = { ...summary };
    evidence.requests = probe.requests.map(({ kind, chars, sha256: digest }) => ({ kind, chars, sha256: digest }));
    evidence.toolGrantsBeforeClose = activeNames;
    evidence.summary = summaryEntry;
  } finally {
    if (gateway) await gateway.close(context);
    evidence.checks = checks;
    evidence.status = collectorStatus(checks);
  }
}

async function runSecondPhase(core, stateDir, evidence) {
  const { checks, record, require } = collector("phase2", stateDir);
  const previous = JSON.parse(await readFile(join(stateDir, PHASE1_EVIDENCE), "utf8"));
  const context = core.context;
  const probe = buildProbe(core);
  const driver = installer(core, probe, "p2");
  const config = gatewayConfig(core, stateDir);
  let gateway;
  try {
    gateway = await core.openGateway(config, context, {
      models: probe.models,
      ...core.workspaceContextGatewayOptions(config),
    });
    const conversation = await gateway.conversationFor(SESSION_KEY, context);

    // Fresh process, same durable conversation.
    require("reopen.stable_conversation_identity", conversation.id === previous.conversationId,
      `${conversation.id} vs ${previous.conversationId}`);
    const resumed = (await gateway.listToolGrants(SESSION_KEY, context)).map((grant) => grant.name);
    require("reopen.grants_persisted", resumed.includes("read") && resumed.includes("write"), resumed.join(","));

    // The critical fresh-process request: fact through the summary, not the raw turn.
    await driver.send(conversation, context,
      "Which acceptance code do you remember from the earlier instruction?",
      [core.fauxAssistantMessage("The earlier instruction recorded an acceptance code.")]);
    const request = probe.requests[0];
    require("reopen.compaction_summary_present", request.text.includes(COMPACTION_PREFIX));
    require("reopen.summary_carries_early_fact", request.text.includes(FACT));
    require("reopen.raw_turn_absent", !request.text.includes(SENTINEL));
    require("reopen.fact_not_in_system_prompt", !request.prompt.includes(FACT));
    require("reopen.bootstrap_rediscovered", request.prompt.includes(BOOTSTRAP_MARKER));
    require("reopen.loaded_memory_present", request.prompt.includes(MEMORY_MARKER));
    require("reopen.memory_manifest_rediscovered",
      request.prompt.includes(`\`${TOPIC_PATH}\` (topic`) && request.prompt.includes(TOPIC_DESCRIPTION));
    require("reopen.skill_summary_present", request.prompt.includes(SKILL_NAME) && request.prompt.includes(SKILL_DESCRIPTION));
    require("reopen.skill_body_absent_before_load", !request.prompt.includes(SKILL_BODY));

    // Revocation still holds in a fresh process.
    const revoked = (await gateway.revokeTools(SESSION_KEY, ["write"], context)).map((grant) => grant.name);
    require("reopen.revoke_persisted", !revoked.includes("write") && revoked.includes("read"), revoked.join(","));

    // Skill body and topic memory on demand, with the reopened read grant.
    await driver.send(conversation, context,
      "Load the note-keeping skill and read the topic memory named in context.",
      [
        core.fauxAssistantMessage([
          core.fauxToolCall("skill", { name: SKILL_NAME }),
          core.fauxToolCall("read", { path: TOPIC_PATH }),
        ], { stopReason: "toolUse" }),
        core.fauxAssistantMessage("Skill and topic memory reviewed."),
      ]);
    const results = toolResultsOf(probe.requests.at(-1).text);
    const skillResults = results.filter((result) => result.toolName === "skill" && !result.isError);
    const readResults = results.filter((result) => result.toolName === "read" && !result.isError);
    require("reopen.skill_body_on_demand", skillResults.length === 1 && skillResults[0].text.includes(SKILL_BODY), skillResults[0]?.text);
    require("reopen.memory_read_granted", readResults.length === 1 && readResults[0].text.includes(FACT), readResults[0]?.text);

    evidence.conversationId = conversation.id;
    evidence.requests = probe.requests.map(({ kind, chars, sha256: digest }) => ({ kind, chars, sha256: digest }));
  } finally {
    if (gateway) await gateway.close(context);
    evidence.checks = checks;
    evidence.status = collectorStatus(checks);
  }
}

function collectorStatus(checks) {
  return checks.length > 0 && checks.every((check) => check.status === "pass") ? "pass" : "fail";
}

async function runPhase(phase, stateDir) {
  const evidencePath = join(stateDir, phase === "first" ? PHASE1_EVIDENCE : PHASE2_EVIDENCE);
  const core = await loadCore();
  const evidence = {
    phase,
    mode: "offline-synthetic",
    provider: { kind: "faux", model: `${PROVIDER}/${MODEL_ID}` },
    checks: [],
    status: "fail",
  };
  try {
    if (phase === "first") await runFirstPhase(core, stateDir, evidence);
    else await runSecondPhase(core, stateDir, evidence);
  } catch (error) {
    evidence.checks.push({
      id: `${phase === "first" ? "phase1" : "phase2"}.run_failed`,
      status: "fail",
      detail: redact(error?.message ?? String(error), stateDir),
    });
    evidence.status = "fail";
    evidence.error = redact(error?.stack ?? String(error), stateDir).split("\n").slice(0, 6).join("\n");
  }
  evidence.status = collectorStatus(evidence.checks);
  await writeFile(evidencePath, `${JSON.stringify(evidence, null, 2)}\n`, "utf8");
  process.exit(evidence.status === "pass" ? 0 : 1);
}

