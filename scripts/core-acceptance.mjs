async function generateWorkspace(stateDir) {
  const workspace = join(stateDir, "workspace");
  const files = {
    "AGENTS.md": [
      "# Synthetic acceptance workspace",
      "",
      BOOTSTRAP_MARKER,
      "",
      "This workspace is generated by the offline core acceptance runner and deleted afterwards.",
      "It contains no personal data and is not a real workspace.",
      "",
    ].join("\n"),
    "memory/MEMORY.md": [
      "# Loaded memory",
      "",
      MEMORY_MARKER,
      "",
      "The acceptance runner loads this file into the prompt through the real workspace loader.",
      "",
    ].join("\n"),
    "skills/note-keeping/SKILL.md": [
      "---",
      `name: ${SKILL_NAME}`,
      `description: ${SKILL_DESCRIPTION}`,
      "---",
      "",
      "# Note keeping",
      "",
      SKILL_BODY,
      "",
      "Keep short notes in topic memory. This body must reach the model only through the skill tool.",
      "",
    ].join("\n"),
  };
  for (const [relativePath, content] of Object.entries(files)) {
    const path = join(workspace, ...relativePath.split("/"));
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, "utf8");
  }
  await mkdir(join(workspace, "memory", "topics"), { recursive: true });
  return workspace;
}

