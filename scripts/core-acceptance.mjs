function runChild(args, cwd) {
  return new Promise((done) => {
    const started = Date.now();
    const child = spawn(process.execPath, args, { cwd, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    let timedOut = false;
    const collect = (target) => (chunk) => {
      const text = String(chunk);
      if (target === "stdout") stdout = (stdout + text).slice(-16_384);
      else stderr = (stderr + text).slice(-16_384);
    };
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", collect("stdout"));
    child.stderr.on("data", collect("stderr"));
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGKILL");
    }, CHILD_TIMEOUT_MS);
    const finish = (code, signal, error) => {
      clearTimeout(timer);
      done({ code, signal, error, timedOut, stdout, stderr, durationMs: Date.now() - started });
    };
    child.once("error", (error) => finish(null, null, error));
    child.once("exit", (code, signal) => finish(code, signal, undefined));
  });
}

async function readEvidence(stateDir, name) {
  try {
    return JSON.parse(await readFile(join(stateDir, name), "utf8"));
  } catch {
    return undefined;
  }
}

async function run() {
  const started = Date.now();
  const checks = [];
  const record = (id, ok, detail) => {
    checks.push({ id: `runner.${id}`, status: ok ? "pass" : "fail", ...(detail === undefined ? {} : { detail }) });
    return ok;
  };
  let stateDir;
  const phases = {};
  try {
    stateDir = await mkdtemp(join(tmpdir(), "nanobot-core-acceptance-"));
    const workspace = await generateWorkspace(stateDir);
    const generated = await Promise.all([
      access(join(workspace, "AGENTS.md")),
      access(join(workspace, "memory", "MEMORY.md")),
      access(join(workspace, "skills", "note-keeping", "SKILL.md")),
    ]).then(() => true, () => false);
    record("synthetic_workspace_generated", generated);

    const first = await runChild([SCRIPT, "--phase=first", `--state=${stateDir}`], ROOT);
    phases.first = { exitCode: first.code, signal: first.signal, timedOut: first.timedOut, durationMs: first.durationMs };
    record("phase1_process", first.code === 0 && !first.timedOut,
      first.code === 0 && !first.timedOut
        ? undefined
        : redact(first.error?.message ?? first.stderr.split("\n").slice(-4).join(" "), stateDir));
    const firstEvidence = await readEvidence(stateDir, PHASE1_EVIDENCE);
    record("phase1_evidence", firstEvidence !== undefined && firstEvidence.status === "pass");

    // Independent check of the actual write, outside the child's claims.
    let topicOnDisk = "";
    try {
      topicOnDisk = await readFile(join(workspace, "memory", "topics", "acceptance.md"), "utf8");
    } catch {
      topicOnDisk = "";
    }
    record("memory_write_on_disk", topicOnDisk.includes(FACT) && topicOnDisk.includes(TOPIC_DESCRIPTION));

    const second = await runChild([SCRIPT, "--phase=reopen", `--state=${stateDir}`], ROOT);
    phases.reopen = { exitCode: second.code, signal: second.signal, timedOut: second.timedOut, durationMs: second.durationMs };
    record("phase2_process", second.code === 0 && !second.timedOut,
      second.code === 0 && !second.timedOut
        ? undefined
        : redact(second.error?.message ?? second.stderr.split("\n").slice(-4).join(" "), stateDir));
    const secondEvidence = await readEvidence(stateDir, PHASE2_EVIDENCE);
    record("phase2_evidence", secondEvidence !== undefined && secondEvidence.status === "pass");

    const childChecks = [...(firstEvidence?.checks ?? []), ...(secondEvidence?.checks ?? [])];
    checks.push(...childChecks);
    const allPass = checks.length > 0 && checks.every((check) => check.status === "pass");
    const report = {
      runner: "core-acceptance",
      version: 1,
      status: allPass ? "pass" : "fail",
      mode: "offline-synthetic",
      provider: { kind: "faux", model: `${PROVIDER}/${MODEL_ID}`, network: false },
      notRun: NOT_RUN,
      limits: { childTimeoutMs: CHILD_TIMEOUT_MS, compactionWaitMs: COMPACTION_WAIT_MS },
      durationMs: Date.now() - started,
      checks,
      counts: counts(checks),
      phases,
    };
    const text = `${JSON.stringify(report, null, 2)}\n`;
    const output = argValue("--output=");
    if (output !== undefined) {
      try {
        await writeFile(resolve(output), text, { flag: "wx" });
      } catch (error) {
        if (error?.code === "EEXIST") {
          process.stderr.write(`core-acceptance: refusing to overwrite existing output ${resolve(output)}\n`);
          return 2;
        }
        throw error;
      }
    }
    process.stdout.write(text);
    return allPass ? 0 : 1;
  } catch (error) {
    process.stderr.write(`core-acceptance: ${error?.message ?? String(error)}\n`);
    return 1;
  } finally {
    if (stateDir !== undefined) await rm(stateDir, { recursive: true, force: true });
  }
}

const phase = argValue("--phase=");
const stateDir = argValue("--state=");
if (phase === undefined) {
  const code = await run();
  process.exit(code);
}
if (stateDir === undefined) {
  process.stderr.write("core-acceptance: --phase requires --state\n");
  process.exit(2);
}
await runPhase(phase, stateDir);
