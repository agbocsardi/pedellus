#!/usr/bin/env node
/**
 * Offline core acceptance runner.
 *
 * Exercises the actual `openGateway` build over a generated, disposable
 * workspace with a faux pi-ai provider: real Markdown context discovery, an
 * on-demand skill body, topic-memory read/write through expiring grants, a
 * native Durable manual compaction, and a fresh Node process that reopens the
 * same store and must recall an early fact through the summary only.
 *
 * No provider network request, credential, personal workspace, channel, or
 * external fixture is involved. The run is offline-only and the report states
 * what it did not run.
 *
 * Usage:
 *   npm run test:core-acceptance           # prints one JSON report
 *   node scripts/core-acceptance.mjs --output=<path>   # also writes it, never overwrites
 *
 * Exit codes: 0 all checks pass, 1 a check failed, 2 usage/output error.
 */
import { spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { access, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT = fileURLToPath(import.meta.url);
const ROOT = resolve(dirname(SCRIPT), "..");
const PHASE1_EVIDENCE = "evidence-phase1.json";
const PHASE2_EVIDENCE = "evidence-phase2.json";
const CHILD_TIMEOUT_MS = 120_000;
const COMPACTION_WAIT_MS = 20_000;

/** Synthetic markers. They are generated here and never derived from real data. */
const SESSION_KEY = "core-acceptance:session";
const PROVIDER = "core-acceptance-faux";
const MODEL_ID = "synthetic";
const FACT = "AURORA-7391";
const SENTINEL = "RAW-TURN-SENTINEL-8842";
const SKILL_NAME = "note-keeping";
const SKILL_DESCRIPTION = "Synthetic offline note-keeping instructions for the core acceptance run";
const SKILL_BODY = "SKILL_BODY_MARKER_5F3A";
const BOOTSTRAP_MARKER = "ACCEPTANCE_BOOTSTRAP_ALPHA";
const MEMORY_MARKER = "MEMORY_MD_MARKER_7C1D";
const TOPIC_PATH = "memory/topics/acceptance.md";
const TOPIC_DESCRIPTION = "Synthetic acceptance topic written through a granted tool";
const COMPACTION_PREFIX = "The conversation history before this point was compacted into the following summary";

const NOT_RUN = Object.freeze([
  "real-model provider calls (offline faux provider only)",
  "A/B harness fixture comparison and parity claims",
  "channels, Telegram delivery and scheduled outbound sends",
  "credentials, personal workspace and live data",
  "Bubblewrap sandbox backend",
]);

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

function sleep(ms) {
  return new Promise((done) => setTimeout(done, ms));
}

function argValue(prefix) {
  const found = process.argv.find((argument) => argument.startsWith(prefix));
  return found === undefined ? undefined : found.slice(prefix.length);
}

function redact(text, stateDir) {
  return String(text)
    .split(join(stateDir, "workspace")).join("<workspace>")
    .split(join(stateDir, "data")).join("<data>")
    .split(stateDir).join("<state>");
}

function collector(prefix, stateDir) {
  const checks = [];
  const detailOf = (detail) => {
    if (detail === undefined) return undefined;
    const text = redact(detail, stateDir);
    return text.length > 800 ? `${text.slice(0, 800)}...` : text;
  };
  const record = (id, ok, detail) => {
    checks.push({
      id: `${prefix}.${id}`,
      status: ok ? "pass" : "fail",
      ...(detail === undefined ? {} : { detail: detailOf(detail) }),
    });
    return ok;
  };
  const requireCheck = (id, ok, detail) => {
    record(id, ok, detail);
    if (!ok) throw new Error(`acceptance check failed: ${prefix}.${id}`);
  };
  return { checks, record, require: requireCheck };
}

function counts(checks) {
  return {
    pass: checks.filter((check) => check.status === "pass").length,
    fail: checks.filter((check) => check.status === "fail").length,
    total: checks.length,
  };
}

