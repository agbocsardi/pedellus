function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

function sleep(ms) {
  return new Promise((done) => setTimeout(done, ms));
}

function argValue(prefix) {
  const found = process.argv.find((argument) => argument.startsWith(prefix));
  return found === undefined ? undefined : found.slice(prefix.length);
}

function redact(text, stateDir) {
  return String(text)
    .split(join(stateDir, "workspace")).join("<workspace>")
    .split(join(stateDir, "data")).join("<data>")
    .split(stateDir).join("<state>");
}

function collector(prefix, stateDir) {
  const checks = [];
  const detailOf = (detail) => {
    if (detail === undefined) return undefined;
    const text = redact(detail, stateDir);
    return text.length > 800 ? `${text.slice(0, 800)}...` : text;
  };
  const record = (id, ok, detail) => {
    checks.push({
      id: `${prefix}.${id}`,
      status: ok ? "pass" : "fail",
      ...(detail === undefined ? {} : { detail: detailOf(detail) }),
    });
    return ok;
  };
  const requireCheck = (id, ok, detail) => {
    record(id, ok, detail);
    if (!ok) throw new Error(`acceptance check failed: ${prefix}.${id}`);
  };
  return { checks, record, require: requireCheck };
}

function counts(checks) {
  return {
    pass: checks.filter((check) => check.status === "pass").length,
    fail: checks.filter((check) => check.status === "fail").length,
    total: checks.length,
  };
}

